            if (ks != null && file(ks).exists()) {
                storeFile = file(ks)
                storePassword = System.getenv("EASYPRINT_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("EASYPRINT_KEY_ALIAS")
                keyPassword = System.getenv("EASYPRINT_KEY_PASSWORD")
